-- DS-HOST-001: THE DeltaSync-1.0 HOST
-- ============================================================================
-- Step 2 of THE DELTA RELEASE (docs/DELTA_RELEASE.md section 5). The operator, 2026-09-11: "rip it
-- out and use the library" -- TOGBank's own sync frameworks give way to DeltaSync. Until this,
-- DeltaSync was a declared dependency that nothing called: Core carried its own byte-identical
-- copies of the library's checksum and `<AceSerialized>\030<checksum>\031END` envelope (~140 lines,
-- the "duplicate envelope code" LIBREQ-DS-003 named). Those copies are deleted; the three public
-- methods below delegate to the host. deltahost_spec pins the envelope for a fixed payload as a
-- literal captured from Core's OWN implementation before the delegation, so "byte-identical" is
-- proven rather than reasoned -- every peer on every prior version parses this exact framing.
--
-- What the host carries: the envelope and the checksum (DS-HOST-001), and since step 3b the DATA
-- LEG of every sync -- a requester's QUERY naming the canon it holds (`host:RequestData`), and the
-- provider's RESPONSE carrying the delta chain, the snapshot or a no-change (`host:SendData`;
-- Modules/Inventory/Sync.lua). Its seven comm prefixes are registered at creation. The numbered
-- handshake (P2P-035) is still TOGBank's own layer on `togbank-rr` until LIBREQ-DS-008 moves it into
-- the library; the host's InitP2P is deliberately NOT called, because per-item hash offers are the
-- design banker numbers replaced.
--
-- DEBUG: the host gets a LOGGER (LIBREQ-DS-003's shape), so DeltaSync claims no chat tab and does
-- no filtering of its own. Every library line lands in Output:Debug under the DELTASYNC category,
-- with the library's own category as the tag -- and its tag, when it has one, joined on
-- (`COMMS-SEND`) -- so one TOGBank toggle gates the library and its lines still filter.
local deltaHost

--- Route a DeltaSync debug call into Output. The library calls its logger with the RAW arguments
--- of lib:Debug -- (category, tag, fmt, ...) / (category, fmt, ...) / (fmt, ...) -- and leaves the
--- resolution to the host. The rule mirrors Output:Debug's own DEBUG-001 shape test: a bare
--- SCREAMING token followed by at least one more argument is a category or a tag.
local DS_CATEGORIES = {
    INIT = true, HASH = true, COMMS = true, DELTA = true,
    VALIDATE = true, SERIALIZE = true, P2P = true, ROSTER = true,
}
local function DeltaSyncLogger(fmt, ...)
    if type(fmt) == "string" and DS_CATEGORIES[fmt] and select("#", ...) > 0 then
        local category, second = fmt, (select(1, ...))
        if type(second) == "string" and select("#", ...) > 1 and second:match("^[%u%d%-_]+$") then
            return TOGBankClassic_Output:Debug("DELTASYNC", category .. "-" .. second, select(2, ...))
        end
        return TOGBankClassic_Output:Debug("DELTASYNC", category, ...)
    end
    return TOGBankClassic_Output:Debug("DELTASYNC", fmt, ...)
end

-- ---------------------------------------------------------------------------------------------
-- DS-HOST-002: THE TRANSPORT PROXY, and the one thing it adds -- a per-send completion.
-- ---------------------------------------------------------------------------------------------
-- DeltaSync sends through `aceAddon:SendCommMessage` and receives through `aceAddon:RegisterComm`;
-- that is the whole of what it asks of the object. It exposes no "this send has LEFT" hook -- its
-- `onSendFailed` fires only for a refusal, and `sendsDelivered` is a counter with no identity. The
-- P2P send slot (P2P-024/028) must be released when the reply has drained, not when it was queued,
-- or three queued snapshots count as no load and the cap admits a fourth. LIBREQ-DS-009 asks the
-- library for the callback; until it ships, this proxy is the reference implementation: it forwards
-- both methods to Core unchanged and, on the way through, chains the delivery callback so a watcher
-- registered for (prefix, target) hears the whole-message verdict exactly once.
--
-- A watcher is CONSUMED by the first send matching its key. `host:SendData` sends synchronously
-- inside the call, so "register, then SendData" cannot be interleaved by another send to the same
-- target; a send the library refuses before reaching the proxy (its roster online-guard) never
-- consumes the watcher, which is why callers Unwatch on a false return.
local hostSendWatchers = {}

--- Hear the verdict of the NEXT host send on `prefix` to `target`: fn(delivered, reason).
function TOGBankClassic_Core:WatchHostSend(prefix, target, fn)
    hostSendWatchers[tostring(prefix) .. "|" .. tostring(target)] = fn
end

function TOGBankClassic_Core:UnwatchHostSend(prefix, target)
    hostSendWatchers[tostring(prefix) .. "|" .. tostring(target)] = nil
end

local function HostTransport()
    local Core = TOGBankClassic_Core
    return {
        name = "TOGBankClassic",
        -- Read by the library's status report only: whether the callback is one terminal verdict.
        __AceCommQueue_embedded = Core.__AceCommQueue_embedded,
        RegisterComm = function(_, prefix, handler)
            return Core:RegisterComm(prefix, handler)
        end,
        SendCommMessage = function(_, prefix, text, distribution, target, prio, callbackFn, callbackArg)
            local key = tostring(prefix) .. "|" .. tostring(target)
            local watcher = hostSendWatchers[key]
            hostSendWatchers[key] = nil
            local function onResult(arg, sent, total, delivered, reason)
                if callbackFn then callbackFn(arg, sent, total, delivered, reason) end
                -- TERMINAL means the message's fate is known: it all went (sent >= total), or it
                -- did not go at all -- refused (`false`), or never attempted (`nil`: the raid
                -- guard above reports (0, 0, nil)). Under AceCommQueue there is exactly one
                -- callback and it is terminal whatever it says; the `delivered ~= true` half is
                -- what keeps a refusal terminal if a per-chunk transport ever reports one early.
                if watcher and (delivered ~= true or (total or 0) == 0 or (sent or 0) >= total) then
                    local fn = watcher
                    watcher = nil
                    fn(delivered == true, reason)
                end
            end
            return Core:SendCommMessage(prefix, text, distribution, target, prio, onResult, callbackArg)
        end,
    }
end

--- The host, created on first use. Lazy rather than only in OnInitialize because the envelope is
--- reachable before OnInitialize runs (a spec that loads Core and serializes; a comm handler bound
--- early), and a host that does not exist yet must not turn into a nil index at the first send.
---@return table host the DeltaSync-1.0 host object
function TOGBankClassic_Core:DeltaHost()
    if deltaHost then return deltaHost end
    local DS = LibStub("DeltaSync-1.0")
    deltaHost = DS:NewHost({
        namespace = "TOGBankClassic",
        aceAddon  = HostTransport(),
        logger    = DeltaSyncLogger,
        -- THE DATA LEG (THE DELTA RELEASE step 3b): a QUERY names the canon a requester holds and
        -- the alt it wants; a RESPONSE is the chain, the snapshot, or a no-change. Inventory/Sync
        -- owns both directions; the closures look it up at call time because Core loads last.
        onDataRequest = function(sender, baseline)
            local Sync = TOGBankClassic_Inventory_Sync
            if Sync then Sync:OnDataRequest(sender, baseline) end
        end,
        onDataReceived = function(sender, data, len)
            local Sync = TOGBankClassic_Inventory_Sync
            if Sync then Sync:OnDataReceived(sender, data, len) end
        end,
        -- A send the client REFUSED -- the message never left. Worth a warning-level line: it is
        -- the failure that otherwise looks like a quiet peer.
        onSendFailed = function(info)
            TOGBankClassic_Output:Debug("DELTASYNC", "COMMS-SKIP",
                "send refused by the client: prefix=%s dist=%s target=%s bytes=%s",
                tostring(info and info.prefix), tostring(info and info.distribution),
                tostring(info and info.target), tostring(info and info.bytes))
        end,
    })
    return deltaHost
end

--- The multiplicative checksum DeltaComms feeds the hash input string through (HASH-PIN-001). A
--- STRING through the library's revision-1 ComputeHash is exactly that checksum over exactly those
--- bytes (SerializeForHash renders a string as itself); a non-string answers 0, as before.
function TOGBankClassic_Core:Checksum(str)
    if type(str) ~= "string" then return 0 end
    return self:DeltaHost():ComputeHash(str)
end

-- Serialize data with appended checksum and stop-marker for integrity verification.
-- Wire format:  <AceSerialized> \030 <checksum> \031END  -- the host's, byte for byte.
function TOGBankClassic_Core:SerializeWithChecksum(data)
    return self:DeltaHost():SerializeWithChecksum(data)
end

-- Deserialize data and verify integrity; returns success, data (or false, error) -- AceSerializer's
-- two-return contract, which the host keeps. The host runs the stop-marker and CRC checks and logs
-- an INTEGRITY-MISMATCH line (through the logger above) when they disagree; what stays here is the
-- tester opt-in chat alert, which the library rightly does not own.
--
-- Optional ctx table for richer diagnostics: { sender, prefix, distribution }
---@param message string
---@param ctx? table
function TOGBankClassic_Core:DeserializeWithChecksum(message, ctx)
    local ok, result = self:DeltaHost():DeserializeWithChecksum(message, ctx)
    if not ok and type(result) == "string" and result:find("CRC mismatch", 1, true)
        and TOGBankClassic_Options and TOGBankClassic_Options:IsIntegrityCheckDiagnosticsEnabled() then
        DEFAULT_CHAT_FRAME:AddMessage("|cFFFF0000[TOGBankClassic ERROR]|r Integrity mismatch: " ..
            "message complete but CRC failed. from=" .. tostring(ctx and ctx.sender or "?") ..
            " prefix=" .. tostring(ctx and ctx.prefix or "?") ..
            " dist=" .. tostring(ctx and ctx.distribution or "?") ..
            " bytes=" .. tostring(type(message) == "string" and #message or 0) ..
            " (" .. result .. ") — please report to developers!")
    end
    return ok, result
end

