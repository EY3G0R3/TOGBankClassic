--- The name a directed addon message is ADDRESSED to, from TOGBank's `Name-Realm` spelling: the
--- realm suffix is stripped for a same-realm target, kept for a cross-realm one. THE ONE address
--- rule (peer review F4): SendWhisper and every directed send on the DeltaSync host
--- (Modules/Inventory/Sync.lua) go through it, so the handshake and the data reply are addressed
--- identically by construction -- a reply addressed differently from the request that earned it
--- would be lost while every handshake worked. DeltaSync's guild-mode stamp re-qualifies the
--- target through the roster before writing it (DeltaSyncGuildMode.lua GM:Stamp), so handing the
--- host a stripped same-realm name produces the same stamp a full one would (peer review A4).
---@param target string
---@return string address
function TOGBankClassic_Core:WhisperAddress(target)
    if target and string.find(target, "-") then
        local left, right = string.match(target, "^(.-)%-(.+)$")
        local currentRealm = GetNormalizedRealmName()
        if left and right and currentRealm and right == currentRealm then
            return left
        end
    end
    return target
end

-- Centralized WHISPER send with automatic online check
-- Returns true if sent, false if target offline or send failed
function TOGBankClassic_Core:SendWhisper(prefix, text, target, prio, callbackFn, callbackArg)
    -- Check if target is online
    local isOnline = TOGBankClassic_Guild:IsPlayerOnline(target)
    TOGBankClassic_Output:Debug("PROTOCOL", "WHISPER", "[WHISPER-DEBUG] SendWhisper called: prefix=%s, target=%s, isOnline=%s",
        prefix, target, tostring(isOnline))

    if not isOnline then
        TOGBankClassic_Output:Debug("WHISPER", "SKIP", "[WHISPER-DEBUG] Cannot send %s WHISPER to %s - player is offline", prefix, target)
        return false
    end

    local nameOnly = self:WhisperAddress(target)

    TOGBankClassic_Output:Debug("PROTOCOL", "WHISPER", "[WHISPER-DEBUG] Attempting SendCommMessage: prefix=%s, target=%s, nameOnly=%s", prefix, target, nameOnly)

    -- Send the whisper (AceComm returns nil on success, which is truthy behavior we want)
    self:SendCommMessage(prefix, text, "WHISPER", nameOnly, prio, callbackFn, callbackArg)

    TOGBankClassic_Output:Debug("PROTOCOL", "WHISPER", "[WHISPER-DEBUG] SendCommMessage completed for %s to %s", prefix, nameOnly)

    -- If we got this far, player is online and whisper was sent
    return true
end

function TOGBankClassic_Core:OnInitialize()
    TOGBankClassic_Output:Init()
    TOGBankClassic_Performance:Initialize()
    TOGBankClassic_Database:Init()
    -- DS-HOST-001: stand the DeltaSync host up here, after Output and the database exist, so its
    -- seven prefixes register at login rather than at the first send. Lazy-created otherwise.
    self:DeltaHost()
    TOGBankClassic_Chat:Init()
    TOGBankClassic_Options:Init()
    TOGBankClassic_Chat:RegisterAliasCommands()
    -- ROSTER-003: bind LibGuildRoster's presence callbacks before events register, so no
    -- online/offline transition is missed during login. Idempotent and safe if the library
    -- is absent (falls back to the legacy roster scan).
    TOGBankClassic_Guild:InitRosterCallbacks()
    -- INV2: attach the V2 SavedVariable. Cheap and side-effect free -- it only ensures the
    -- table exists. Done unconditionally rather than behind the switch so that turning
    -- inventoryV2 on mid-session does not need a reload to start collecting.
    if TOGBankClassic_Inventory_Store then
        TOGBankClassic_Inventory_Store:Init()
        -- DOUBLE-001: said out loud, once, so a banker whose counts were doubled knows why they
        -- just changed and that the next scan republishes the corrected record.
        local repaired = TOGBankClassic_Inventory_Store.repaired or 0
        if repaired > 0 then
            TOGBankClassic_Output:Info("Repaired %d bank record(s) that were counting items twice (a received copy stored beside your own scan). The next scan publishes the corrected counts.", repaired)
        end
    end
    TOGBankClassic_UI:Init()

    if TOGBankClassic_ItemHighlight and TOGBankClassic_ItemHighlight.Initialize then
        TOGBankClassic_ItemHighlight:Initialize()
    end

    if TOGBankClassic_TooltipBankerInfo and TOGBankClassic_TooltipBankerInfo.Initialize then
        TOGBankClassic_TooltipBankerInfo:Initialize()
    end

    self:ScheduleRepeatingTimer(function()
        TOGBankClassic_Performance:RecordMemory("periodic")
    end, 300)

    -- Enable VersionCheck-1.0 addon integration
    do
        local VC = LibStub:GetLibrary("VersionCheck-1.0", true)
        if VC and VC.Enable then
            -- Create a host addon object for VersionCheck
            local hostAddon = {
                GetName = function() return "TOGBankClassic" end,
                Version = GetAddOnMetadata("TOGBankClassic", "Version") or "@project-version@"
            }
            VC:Enable(hostAddon)
            TOGBankClassic_Output:Debug("PROTOCOL", "INIT", "VersionCheck-1.0 integration enabled (v%s)", hostAddon.Version)
        end
    end
end

