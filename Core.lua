-- NS-001: aliased as a file-scope local so a foreign global of the same name cannot be read
-- instead. See the header of Modules/Constants.lua.
local COMM_PREFIX_DESCRIPTIONS = TOGBankClassic_Constants.COMM_PREFIX_DESCRIPTIONS

--- The SEND log's name for a prefix. TOGBank's own come from Constants; the DeltaSync host's seven
--- (`togban-q`, `togban-r`, ...) are generated by the library from the namespace, so they are read
--- off the host rather than listed twice -- commprefix_spec pins Constants to the prefixes Chat
--- registers, and the host registers its own.
local hostPrefixNames
local function DescribePrefix(prefix)
    local own = COMM_PREFIX_DESCRIPTIONS[prefix]
    if own then return own end
    if not hostPrefixNames then
        hostPrefixNames = {}
        local host = TOGBankClassic_Core.DeltaHost and TOGBankClassic_Core:DeltaHost()
        for channel, p in pairs(host and host.prefixes or {}) do
            hostPrefixNames[p] = "(DeltaSync " .. channel .. ")"
        end
    end
    return hostPrefixNames[prefix] or "(Unknown)"
end

-- RAID-SYNC-001: the one raid guard, shared with the receive gate and the status bar.
local SyncPausedByRaid = TOGBankClassic_Constants.SyncPausedByRaid

function TOGBankClassic_Core:SendCommMessage(prefix, text, distribution, target, prio, callbackFn, callbackArg)
    local prefixDesc = DescribePrefix(prefix)
    if SyncPausedByRaid() then
        TOGBankClassic_Output:Debug("COMMS", "SUPPRESS", "< (suppressing) %s %s (in raid)", prefix, prefixDesc)
        -- RAID-VISIBILITY-001: say so ONCE per raid membership, in plain chat. The guard is right
        -- (the chat channel is throttled and raid addons need it) but it was invisible -- the
        -- collect and dispatch timers kept printing "no offers" as if the guild were quiet, and the
        -- operator spent an afternoon on 2026-09-12 believing sync was broken: "i was in a raid, do
        -- you stop syncs while in a raid?" -- "i wasn't aware". Reset by the first send after leaving.
        if not self.raidSuppressNoticed then
            self.raidSuppressNoticed = true
            TOGBankClassic_Output:Info("Guild bank sync is paused while you are in a raid group; it resumes when you leave. (Settings > General > Keep syncing in a raid group)")
        end
        -- Unblock the AceCommQueue waiting on this send (0 >= 0 triggers last-chunk detection).
        if callbackFn then callbackFn(callbackArg, 0, 0, nil) end
        return
    end
    self.raidSuppressNoticed = nil
    if not AceComm_SendCommMessage then
        if callbackFn then callbackFn(callbackArg, 0, 0, nil) end
        return
    end

    local bytes = text and #text or 0
    local dest = (target and target ~= "") and (distribution .. "/" .. target) or distribution
    TOGBankClassic_Output:Debug("COMMS", "SEND", "< %s %s to %s (%d bytes)", prefix, prefixDesc, dest, bytes)

    return AceComm_SendCommMessage(self, prefix, text, distribution, target, prio, callbackFn, callbackArg)
end
